const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  load: () => ipcRenderer.invoke('load'),
  save: (cfg) => ipcRenderer.invoke('save', cfg),
  status: () => ipcRenderer.invoke('status'),
  ping: (host) => ipcRenderer.invoke('net:ping', host),
  speed: () => ipcRenderer.invoke('net:speed'),
  liveStart: (host) => ipcRenderer.invoke('net:liveStart', host),
  liveStop: () => ipcRenderer.invoke('net:liveStop'),
  live: () => ipcRenderer.invoke('net:live'),
  sys: () => ipcRenderer.invoke('sys:stats'),
  presets: () => ipcRenderer.invoke('preset:list'),
  presetSave: (slot, macros) => ipcRenderer.invoke('preset:save', slot, macros),
  presetLoad: (slot) => ipcRenderer.invoke('preset:load', slot),
  tools: () => ipcRenderer.invoke('tools:get'),
  toolsSave: (patch) => ipcRenderer.invoke('tools:save', patch),
  pickApp: () => ipcRenderer.invoke('tools:pick'),
  apps: () => ipcRenderer.invoke('tools:apps'),
  runApp: (target) => ipcRenderer.invoke('tools:run', target),
  richPresenceStatus: () => ipcRenderer.invoke('richpresence:status'),
  richPresenceSave: (id) => ipcRenderer.invoke('richpresence:save', id),
  richPresenceStart: () => ipcRenderer.invoke('richpresence:start'),
  richPresenceStop: () => ipcRenderer.invoke('richpresence:stop'),
  richPresencePortal: () => ipcRenderer.invoke('richpresence:portal'),
  onRichPresenceStatus: (cb) => ipcRenderer.on('richpresence:status', (_e, status) => cb(status)),
  appUpdate: () => ipcRenderer.invoke('app:update'),
  clips: () => ipcRenderer.invoke('clip:list'),
  clipCopy: (i) => ipcRenderer.invoke('clip:copy', i),
  clipClear: () => ipcRenderer.invoke('clip:clear'),
  cleanScan: () => ipcRenderer.invoke('clean:scan'),
  cleanRun: () => ipcRenderer.invoke('clean:run'),
  dlCheck: () => ipcRenderer.invoke('dl:check'),
  dlUpdate: () => ipcRenderer.invoke('dl:update'),
  dlAnalyze: (u) => ipcRenderer.invoke('dl:analyze', u),
  dlStart: (o) => ipcRenderer.invoke('dl:start', o),
  dlStop: () => ipcRenderer.invoke('dl:stop'),
  dlFolder: () => ipcRenderer.invoke('dl:folder'),
  dlSite: (w) => ipcRenderer.invoke('dl:site', w),
  onDlProgress: (cb) => ipcRenderer.on('dl:progress', (_e, m) => cb(m)),
  soundboardPick: () => ipcRenderer.invoke('soundboard:pick'),
  onSoundboardPlay: (cb) => ipcRenderer.on('soundboard:play', (_e, id) => cb(id)),
  wifi: () => ipcRenderer.invoke('net:wifi'),
  dnsSet: (which) => ipcRenderer.invoke('net:dnsSet', which),
  overlay: (on) => ipcRenderer.invoke('ovl:set', on),
  hud: () => ipcRenderer.invoke('ovl:cfg'),
  hudSet: (h) => ipcRenderer.invoke('ovl:save', h),
  onAlert: (cb) => ipcRenderer.on('ovl:alert', (_e, m) => cb(m)),
});
